/** Offline UI smoke test. Does not require a browser, an API key or a paid request. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=fs.readFileSync(path.join(root,'src','app.js'),'utf8').replace(/\(async\(\)=>\{await restoreImages\(\);[\s\S]*?\}\)\(\);\s*$/, '');
const elements=new Map();
const el=id=>{if(!elements.has(id))elements.set(id,{innerHTML:'',addEventListener(){},scrollIntoView(){},appendChild(){}});return elements.get(id)};
const document={querySelector:s=>el(s),querySelectorAll:()=>[],addEventListener(){},createElement:()=>({className:'',textContent:'',remove(){}})};
const stored=new Map();
const context=vm.createContext({document,localStorage:{getItem:k=>stored.get(k)||null,setItem:(k,v)=>stored.set(k,v)},console,structuredClone,Date,Math,URL,requestAnimationFrame:()=>{},scrollTo:()=>{},setTimeout:()=>0});
vm.runInContext(source,context);
const run=expr=>vm.runInContext(expr,context);
run('refreshMetrics=async()=>{};updateEditionPreviews=async()=>{};');
const init=run('fullNav()+hero()+renderDrift()');
assert.match(init,/<h1>DRIFT<span>\.<\/span><\/h1>/);
assert.match(init,/Choose a reference/);
assert.match(init,/distance-option/);
assert.match(run('ticker()'),/ticker-wrap/);
assert.equal((init.match(/class=\"distance-option /g)||[]).length,3);
assert.match(init,/Explore designs/);
assert.match(init,/Review your design/);
assert.match(init,/Generate 2 with AI|Try 2 free studies/);
await run(`handleAction({dataset:{action:'distance',distance:'experimental'}})`);
assert.equal(run('state.distance'),'experimental');
run(`libraryMode='reference'`);
assert.equal((run('libraryModal()').match(/class="library-item"/g)||[]).length,8);
run(`chooseLibraryArtwork('04-electric','reference')`);
assert.equal(run('reference().title'),'Electric Current');
run(`chooseLibraryArtwork('06-signal','study')`);
assert.equal(run('selected().status'),'review');
await run(`handleAction({dataset:{action:'approve'}})`);
assert.equal(run('selected().status'),'approved');
await run(`handleAction({dataset:{action:'use-in-editions'}})`);
assert.equal(run('state.route'),'editions');
const campaign=run('fullNav()+hero()+renderEditions()');
assert.match(campaign,/<h1>LIVING EDITIONS<span>\.<\/span><\/h1>/);
assert.match(campaign,/Campaign details/);
assert.match(campaign,/Your campaign/);
assert.match(campaign,/edition-img-poster/);
assert.match(campaign,/edition-img-story/);
assert.match(campaign,/edition-img-banner/);
assert.ok(!campaign.includes('FIND THE DRIFT'));
console.log('PASS — shared page headers, library selection, approval, handoff, and campaign UI');
